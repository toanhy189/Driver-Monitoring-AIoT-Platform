/* Run only through backend/tests/run_alert_video_browser.py.
   All accounts, video and DB are disposable; no MQTT or physical outputs. */
const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE);

(async () => {
  const fixture = JSON.parse(fs.readFileSync(process.env.QA_FIXTURE, 'utf8'));
  assert.match(fixture.base_url, /^http:\/\/127\.0\.0\.1:\d+$/);
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const steps = [];
  const errors = [];
  async function session(role, hash) {
    const context = await browser.newContext({ acceptDownloads: true });
    await context.addInitScript(token => localStorage.setItem('access_token', token), fixture.tokens[role]);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(fixture.base_url + '/' + hash);
    await page.getByRole('button', { name: 'Mở tài khoản', exact: true }).waitFor();
    return { context, page };
  }
  try {
    const { context, page } = await session('Customer', '#/alerts');
    const row = page.locator('tbody tr').filter({ hasText: 'Mức 1' });
    await row.getByRole('button', { name: 'Xem video', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const player = dialog.locator('video');
    await player.waitFor();
    await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
    const metadata = await player.evaluate(video => ({ duration: video.duration, width: video.videoWidth, height: video.videoHeight }));
    assert.ok(metadata.duration > 0 && metadata.width > 0 && metadata.height > 0);
    await player.evaluate(video => video.play());
    await page.waitForFunction(() => document.querySelector('video')?.currentTime > .1);
    await player.evaluate(video => { video.pause(); video.currentTime = .6; });
    await page.waitForFunction(() => {
      const video = document.querySelector('video');
      return video && !video.seeking && video.currentTime >= .5;
    });
    steps.push('Customer opens alert clip, decodes H.264, plays and seeks in Edge');
    assert.equal(await dialog.getByRole('button', { name: 'Xóa video', exact: true }).count(), 0);
    assert.ok(await page.getByRole('button', { name: 'Đánh dấu đã xem', exact: true }).count() > 0);
    const downloadEvent = page.waitForEvent('download');
    await dialog.getByRole('button', { name: 'Tải video gốc', exact: true }).click();
    const download = await downloadEvent;
    const hash = crypto.createHash('sha256').update(fs.readFileSync(await download.path())).digest('hex');
    assert.equal(hash, fixture.original_sha256);
    steps.push('Original download is byte-identical; Customer can mark read and cannot delete video');
    await dialog.getByRole('button', { name: 'Đóng video', exact: true }).click();
    await row.getByText('Đã kết thúc', { exact: true }).waitFor();
    await row.getByText('Bạn chưa xem', { exact: true }).waitFor();
    await row.getByRole('button', { name: 'Đánh dấu đã xem', exact: true }).click();
    const seenDialog = page.getByRole('alertdialog', { name: 'Đã đánh dấu là đã xem', exact: true });
    await seenDialog.getByText('Đã lưu xác nhận cho tài khoản của bạn.', { exact: false }).waitFor();
    await seenDialog.getByRole('button', { name: 'Xác nhận', exact: true }).click();
    await row.getByText('✓ Đã đánh dấu', { exact: true }).waitFor();
    await row.getByText('Đã kết thúc', { exact: true }).waitFor();
    await row.getByRole('button', { name: 'Xem lệnh', exact: true }).click();
    await page.getByRole('heading', { name: `Lệnh của cảnh báo #${fixture.linked_alert_id}`, exact: true }).waitFor();
    const commandTable = page.getByRole('region', { name: 'Danh sách lệnh', exact: true });
    await commandTable.getByText('Thiết bị đã hoàn tất', { exact: true }).waitFor();
    assert.equal(await commandTable.getByText('COMMAND_EXPIRED', { exact: true }).count(), 0);
    assert.ok(page.url().endsWith(`#/devices/${fixture.target_id}/commands?alert_id=${fixture.linked_alert_id}`));
    await page.reload();
    await commandTable.getByText('Thiết bị đã hoàn tất', { exact: true }).waitFor();
    await page.goto(fixture.base_url + `/#/devices/${fixture.target_id}/commands`);
    await commandTable.getByText('COMMAND_EXPIRED', { exact: true }).waitFor();
    await commandTable.getByText('Thiết bị đã hoàn tất', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Cảnh báo', exact: true }).click();
    await row.getByText('Bạn đã xem', { exact: true }).waitFor();
    steps.push('Resolved alert stays resolved after Customer marks read; linked commands filter exactly and survive URL reload');
    const forbidden = await page.evaluate(async ({ id, token }) => {
      const result = await fetch(`/api/videos/${id}/playback`, { method: 'POST', headers: { Authorization: `Bearer ${token}` } });
      return result.status;
    }, { id: fixture.unassigned_video_id, token: fixture.tokens.Customer });
    assert.equal(forbidden, 404);
    await page.locator('tbody tr').filter({ hasText: 'Mức 3' }).getByText('Chưa nhận clip', { exact: true }).waitFor();
    await page.locator('tbody tr').filter({ hasText: 'Mức 2' }).getByRole('button', { name: 'Xem video', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Bạn vẫn có thể tải video gốc' }).waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Tải video gốc', exact: true }).isEnabled(), true);
    steps.push('Unassigned camera is denied; pending clip and conversion failure are displayed');
    await context.close();

    const admin = await session('Admin', '#/dashboard');
    await admin.page.getByRole('button', { name: 'Giám sát AI', exact: true }).click();
    await admin.page.getByRole('heading', { name: 'Giám sát AI', exact: true }).waitFor();
    assert.match(admin.page.url(), /#\/monitoring$/);
    await admin.page.goBack();
    assert.match(admin.page.url(), /#\/dashboard$/);
    await admin.page.getByRole('button', { name: 'Giám sát AI', exact: true }).waitFor();
    await admin.page.goForward();
    await admin.page.getByRole('heading', { name: 'Giám sát AI', exact: true }).waitFor();
    await admin.page.getByRole('button', { name: 'Thiết bị', exact: true }).click();
    assert.match(admin.page.url(), /#\/devices$/);
    assert.equal(await admin.page.getByText('vision-archived', { exact: true }).count(), 0);
    await admin.page.getByRole('button', { name: /^Đã ngừng sử dụng/ }).click();
    await admin.page.getByText('vision-archived', { exact: true }).waitFor();
    await admin.page.getByRole('button', { name: /^Thiết bị hiện tại/ }).click();
    await admin.page.getByRole('button', { name: 'Đăng ký thiết bị', exact: true }).click();
    const registration = admin.page.locator('#register-panel');
    assert.equal(await registration.getByLabel('Mã thiết bị (tùy chọn)', { exact: true }).inputValue(), '');
    await registration.getByLabel('Tên thiết bị', { exact: true }).fill('Camera đăng ký thử');
    const kind = registration.getByLabel('Loại thiết bị', { exact: true });
    assert.equal(await kind.inputValue(), '');
    assert.equal(await kind.evaluate(select => select.required), true);
    await kind.selectOption('VISION_NODE');
    await registration.getByLabel('Model phần cứng', { exact: true }).fill('USB webcam');
    await registration.getByRole('button', { name: 'Đăng ký', exact: true }).click();
    const registered = admin.page.getByRole('alertdialog');
    await registered.waitFor();
    const generatedCode = (await registered.innerText()).match(/vision-[a-f0-9]{12}/)[0];
    await registered.getByRole('button', { name: 'Xác nhận', exact: true }).click();
    await admin.page.getByRole('row').filter({ hasText: generatedCode }).getByRole('button', { name: 'Xem chi tiết', exact: false }).click();
    await admin.page.getByRole('heading', { name: 'Thông tin thiết bị', exact: true }).waitFor();
    await admin.page.getByRole('region', { name: 'Thông tin thiết bị', exact: true }).getByText('Camera AI', { exact: true }).waitFor();
    assert.equal(await admin.page.getByRole('heading', {name:'Chạy Camera AI',exact:true}).count(),0);
    const remove = admin.page.getByRole('button', { name: 'Xóa đăng ký', exact: true });
    await remove.waitFor();
    await admin.page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === 'Xóa đăng ký ' && !button.disabled));
    admin.page.once('dialog', dialog => dialog.accept());
    await remove.click();
    await admin.page.getByRole('heading', { name: 'Thiết bị', exact: true }).waitFor();
    assert.equal(await admin.page.getByText(generatedCode, { exact: true }).count(), 0);
    await admin.page.getByRole('button', { name: /^Đã ngừng sử dụng/ }).click();
    await admin.page.getByRole('row').filter({ hasText: 'vision-archived' }).getByRole('button', { name: 'Xem chi tiết', exact: false }).click();
    assert.equal(await admin.page.getByRole('button', { name: /^Khôi phục đăng ký/ }).count(), 0);
    await admin.page.getByRole('button', { name: 'Danh sách thiết bị', exact: true }).click();
    await admin.page.getByRole('row').filter({ hasText: 'vision-setup' }).getByRole('button', { name: 'Xem chi tiết', exact: false }).click();
    await admin.page.getByRole('button', { name: /^Cấp thông tin kết nối/ }).click();
    const configured = admin.page.getByRole('alertdialog');
    await configured.getByText('private-browser-fixture-password',{exact:true}).waitFor();
    assert.equal(await configured.getByRole('button', { name:'Tải cấu hình Camera AI',exact:true }).count(),0);
    await configured.getByRole('button', { name: 'Xác nhận', exact: true }).click();
    await admin.page.waitForFunction(() => document.querySelector('.device-details')?.textContent.includes('PROVISIONED'));
    await admin.page.getByRole('button', { name: 'Danh sách thiết bị', exact: true }).click();
    await admin.page.getByRole('row').filter({ hasText: 'alert-browser' }).getByRole('button', { name: 'Xem chi tiết', exact: false }).click();
    await admin.page.setViewportSize({ width: 320, height: 740 });
    let retireRequests = 0;
    admin.page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith(`/devices/${fixture.target_id}/decommission`)) retireRequests++; });
    await admin.page.getByRole('button', { name: /^Ngừng sử dụng/ }).click();
    let confirmation = admin.page.getByRole('alertdialog');
    await confirmation.getByText('alert-browser', { exact: true }).first().waitFor();
    assert.equal(await confirmation.evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), true);
    assert.equal(retireRequests, 0);
    await confirmation.getByRole('button', { name: 'Hủy', exact: true }).click();
    assert.equal(retireRequests, 0);
    await admin.page.getByRole('button', { name: /^Ngừng sử dụng/ }).click();
    await admin.page.getByRole('alertdialog').waitFor();
    await admin.page.keyboard.press('Escape');
    assert.equal(await admin.page.getByRole('alertdialog').count(), 0);
    assert.equal(retireRequests, 0);
    await admin.page.getByRole('button', { name: /^Ngừng sử dụng/ }).click();
    confirmation = admin.page.getByRole('alertdialog');
    await confirmation.getByRole('button', { name: 'Xác nhận ngừng sử dụng', exact: true }).click();
    await admin.page.getByRole('alertdialog').getByRole('button', { name: 'Xác nhận', exact: true }).click();
    await admin.page.waitForFunction(() => document.querySelector('.device-details')?.textContent.includes('DECOMMISSIONED'));
    assert.equal(retireRequests, 1);
    await admin.page.setViewportSize({ width: 1280, height: 900 });
    steps.push('Admin creates a camera with a generated code and provisions credentials; multi-camera setup and config download are absent; retired devices have no restore button; decommission Cancel sends nothing and Confirm sends one request');
    await admin.page.getByRole('button', { name: 'Quản trị', exact: true }).click();
    assert.match(admin.page.url(), /#\/dashboard$/);
    await admin.page.getByRole('button', { name: 'Cảnh báo', exact: true }).click();
    await admin.page.locator('tbody tr').filter({ hasText: 'Mức 1' }).getByText('Bạn chưa xem', { exact: true }).waitFor();
    await admin.page.locator('tbody tr').filter({ hasText: 'Mức 1' }).getByRole('button', { name: 'Xem video', exact: true }).click();
    await admin.page.getByRole('dialog').getByRole('button', { name: 'Xóa video', exact: true }).waitFor();
    steps.push('Admin switches management/AI, Back/Forward, alerts and retains delete permission');
    await admin.context.close();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ pass: true, scope: 'React build + real FastAPI routes + isolated SQLite + synthetic MPEG4 converted to H264 + installed Edge', steps, page_errors: errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
